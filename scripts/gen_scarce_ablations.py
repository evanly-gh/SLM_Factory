"""Generate the seven data-scarce launchers from their baselines (2026-10-16).

THE ARM. `sms_spam`, `clinc150` and `xlam_bfcl` already ran the data-scarcity question as A/B pairs
(09-16 note, Part III): 100 real rows, mining off, goal pinned at 0.99, synthesis off in arm A and
on in arm B. This extends the scarce setting to the other seven tasks in the ten-task suite, with
two deliberate differences from those pairs:

  * ONE ARM PER TASK, NOT A PAIR. Each launcher is the task's own baseline, starved of real data.
    Synthesis is left exactly as the baseline has it — every one of these seven exports
    `SLM_TEACHER_SYNTH_BYPASS=1`, so synthesis is on — and the comparison is against the
    full-data baseline run in Part I rather than against a no-synth twin.
  * THE GOAL IS LEFT CALIBRATED, not pinned at 0.99. It is set the way the baseline's was: by the
    orchestrator's judge from the teacher measurement, floored at 0.80. So these runs can converge,
    stop early, or raise the goal mid-run exactly as their baselines could, and a difference from
    the baseline is the cost of scarcity under the same stopping rule.

THE FOUR LINES:
  * `SLM_ABLATION_TRAIN_CAP=100` — the initial gold load (eval_setup.py) is capped at 100 rows.
    `topv2` is the one task where the number loaded is not 100: its loader never drops the 669
    SPIS adaptation rows the low-resource protocol is built on, so the cap removes only the
    source-domain fill and the run trains on the protocol's 25-SPIS set alone.
  * `SLM_ABLATION_DISALLOW_MINING=1` — `mine_new_real` reads deeper into the SAME corpus, so a run
    capped at 100 rows would mine straight back to thousands. The cap without the refusal is not a
    scarcity experiment.
  * `SLM_MIN_CURRICULUM_ROWS=50` — the 500-row curriculum floor aborts a run below it on the theory
    that the loader broke. Here the data is absent by construction; 50 leaves room for the
    quality-control passes to drop a few rows, as on the sms_spam pair.
  * `unset SLM_SYNTH_API_MODE` — sbatch forwards the submitting shell's environment, which is how
    run 39361648 silently became a DeepSeek run. This pins the local Qwen teacher the baselines
    used.

Re-running this script is safe: it rewrites the seven files from their current baselines.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

PIPELINE = Path(__file__).resolve().parent.parent / "tests" / "pipeline"

# task -> the baseline run this arm is read against (09-16 note, Part I).
TASKS = {
    "calendar_json": "slm-calendar-json-l40s-39294409 — 0.8748 ast_arg_match, T3 Qwen3.5-2B@Q4_K_M",
    "ner_bc5cdr": "slm-ner-bc5cdr-l40s-39311801 — 0.8532 span_f1, T3 Qwen3.5-2B@Q4_K_M",
    "goemotions": "slm-goemotions-ckpt-39708679 — 0.5979 ekman_macro_f1, T5 Qwen3-4B-Instruct-2507@Q8_0",
    "gec_bea19": "slm-gec-bea19-l40s-39881529 — 0.5647 errant_f05, T5 Qwen3-4B-Instruct-2507@Q8_0",
    "multiconer": "slm-multiconer-l40s-39881531 — 0.6388 micro_f1, T5 Qwen3-4B-Instruct-2507@Q8_0",
    "dialogsum": "slm-dialogsum-l40s-39969104 — 0.4817 rouge_l, T5 Qwen3-4B-Instruct-2507@Q8_0",
    "topv2": "slm-topv2-l40s-39969102 — 0.5990 exact_match, T5 Qwen3-4B-Instruct-2507@Q8_0",
}

HEADER = """#
# ============================================================================================
# ABLATION — DATA SCARCE (100 real rows, mining off, goal calibrated as normal)
#
# Added 2026-10-16, extending the data-scarcity setting from the sms_spam / clinc150 / xlam_bfcl
# pairs (09-16 note, Part III) to the rest of the ten-task suite. GENERATED by
# `scripts/gen_scarce_ablations.py` from `{baseline_script}` — every line below the header is that
# file's, unchanged, plus the four lines at the bottom. Do not hand-edit; change the generator and
# re-run it.
#
# BASELINE: {baseline_log}
#
# Same task, teacher, synthesis setting and model ladder as the baseline. The only change is the
# data: the initial gold load is capped at 100 rows and `mine_new_real` is refused, so the run
# cannot read its way back to the full corpus. Synthesis stays on as in the baseline.
#
# UNLIKE THE THREE EARLIER PAIRS, THE GOAL IS NOT PINNED. It is set the normal way — the
# orchestrator's judge, floored at 0.80 — so the run may converge, stop early, or raise its goal
# exactly as the baseline could, and the gap to the baseline is the cost of scarcity under the
# same stopping rule.
# ============================================================================================"""

ABLATION_EXPORTS = """
export SLM_ABLATION_TRAIN_CAP=100
export SLM_ABLATION_DISALLOW_MINING=1
export SLM_MIN_CURRICULUM_ROWS=50
unset SLM_SYNTH_API_MODE
"""


def build(task: str) -> tuple[Path, str]:
    baseline_script = f"run_{task}_l40s.slurm"
    text = (PIPELINE / baseline_script).read_text()
    job = f"slm-{task.replace('_', '-')}-ablation-scarce-l40s"

    # Rename the job and its log, so the ablation never writes over its baseline's output.
    text = re.sub(r"^#SBATCH --job-name=.*$", f"#SBATCH --job-name={job}", text, flags=re.M)
    text = re.sub(r"^#SBATCH --output=.*$",
                  "#SBATCH --output=/mmfs1/gscratch/intelligentsystems/evanly/SLM_Factory/"
                  f"logs/slurm/{job}-%j.out", text, flags=re.M)

    header = HEADER.format(baseline_script=baseline_script, baseline_log=TASKS[task])

    # Splice the header in after the #SBATCH block, replacing the baseline's leading bare `#`.
    lines = text.splitlines()
    last_sbatch = max(i for i, line in enumerate(lines) if line.startswith("#SBATCH"))
    rest = lines[last_sbatch + 1:]
    if rest and rest[0].strip() == "#":
        rest = rest[1:]
    text = "\n".join(lines[: last_sbatch + 1]) + "\n" + header + "\n" + "\n".join(rest)

    # The exports go immediately BEFORE the body source line, so they are in scope for it.
    source_line = ("source /mmfs1/gscratch/intelligentsystems/evanly/SLM_Factory/tests/pipeline/"
                   "_l40s_task_body.sh")
    assert text.count(source_line) == 1, f"{baseline_script}: expected one body source line"
    text = text.replace(source_line, ABLATION_EXPORTS.strip() + "\n" + source_line)
    if not text.endswith("\n"):
        text += "\n"
    return PIPELINE / f"run_{task}_ablation_scarce_l40s.slurm", text


def main() -> int:
    for task in TASKS:
        path, text = build(task)
        path.write_text(text)
        path.chmod(0o755)
        print(f"wrote {path.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
