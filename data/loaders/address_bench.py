"""address-bench loader — "is the latest line addressed to the assistant?" (2026-10-06).

THE TASK
    A wearable voice assistant hears everything around its wearer. Before it pays for a judge call
    it runs a cheap **gate**: given the recent transcript plus one new line, is that line addressed
    to the assistant?

        input  : the last few transcript lines, plus the latest line and who said it
        output : `addressed` or `not_addressed`

    The gate is the on-device component — it runs on every line, where the judge runs on a few —
    so it is the one worth fine-tuning to a small quantized model, which is what makes it a
    SLM Factory task rather than a prompt-engineering exercise.

WHY THIS IS AN OUT-OF-DISTRIBUTION TASK
    The label is not a property of the line's surface form. "Can you do Thursday at noon?" is
    request-shaped and addressed to a *person*; "Thursday at noon" is a bare fragment and may be an
    answer to something the assistant just asked. The corpus is built so that syntax alone cannot
    separate the classes — the N4 and N10 buckets exist precisely to punish a model that keys on
    wake-word lookalikes and imperative mood. A base model has no pattern to match; the decision
    boundary is what fine-tuning has to supply.

    That puts it with `proactive_listening` and `clinc150` rather than with `sms_spam`, and it is
    the better-posed kind of OOD task: unlike RouterBench, whose label describes a *different
    model's* behaviour and is therefore unknowable from the prompt, the evidence here is genuinely
    in the text — who is speaking, what the Assistant said last, whether a request was ever
    answered.

DATA
    Frozen bundle at `data/local/address_bench/gate_synthetic.jsonl` (6,000 rows), copied from
    `bubble-agent-pipeline/data/bench/gate_synthetic.jsonl` with a manifest and a sha256. **There is
    no HuggingFace mirror and no live fetch**: the corpus was generated by that repo's
    `scripts/build_gate_synthetic.py` and exists nowhere else, so it is vendored the way
    `proactive_listening`'s Google-Drive tarball is, rather than downloaded at run time.

    1,500 addressed / 4,500 not. Twenty buckets, P1-P10 addressed and N1-N10 not, each a named
    failure mode (`P1 explicit_wake_word`, `N5 other_speaker_wake_word`, ...). The bucket rides
    along on every row because the scorer reports accuracy per bucket and categorizes failures by
    it — see `eval/scorers/address_gate.py`.

WHAT THIS LOADER DOES THAT THE UPSTREAM HARNESS DOES NOT
    Upstream feeds a model structured fields and reads a probability off the answer token. This
    pipeline trains and scores on text, so the loader RENDERS each row to a single `text` blob at
    load time:

        Conversation so far:
        Speaker2: where are we meeting
        User: the usual place

        Latest line, User: "Glasses, add lunch with Sam on Thursday at noon."

    Rendering here rather than in the scorer is what keeps the data-rebuild loop simple: a
    synthesized row only has to produce `{text, label}`, exactly as `sms_spam`'s does, instead of
    four structured fields the synthesis path would need to learn to emit and verify. The cost,
    stated: a synthesized row has no `bucket`, so it scores under `synthetic` in the per-bucket
    table rather than joining a real bucket's denominator.

    `--context 8` is upstream's default and is reproduced here as `CONTEXT_LINES`.

SPLIT
    Stratified on (bucket, label) and seeded, so train and eval carry the same bucket mix — a
    random split would leave some of the twenty buckets with single-digit support on the eval side
    and make per-bucket accuracy meaningless. Deduplication happens BEFORE the split, on the
    rendered text, so no copy of a row straddles the contamination firewall (the B44 lesson that
    `sms_spam`'s rewrite encodes).
"""
from __future__ import annotations

import hashlib
import json
import os
import random

from eval.scorers.address_gate import ADDRESSED, NOT_ADDRESSED

LOCAL_BUNDLE = "data/local/address_bench"
CORPUS_FILE = "gate_synthetic.jsonl"

# Upstream's `--context` default. How many trailing transcript lines the model sees.
CONTEXT_LINES = 8

# One split, pinned. A requeued run must rebuild the identical eval set or scores from before and
# after the requeue are not comparable.
EVAL_FRACTION = 0.20
SPLIT_SEED = 20261006

REQUIRED_RAW_FIELDS = ("current_turn", "addressed")


def _normalize(text: str) -> str:
    """Comparison key for duplicate detection. Mirrors the eval firewall's normalization."""
    return " ".join(str(text or "").lower().split())


def render_text(row: dict, n_context: int = CONTEXT_LINES) -> str:
    """One raw corpus row as the single input blob the model sees.

    Mirrors `address_bench/prompts.py::user_message` — same ordering, same `(nothing yet)`
    sentinel, same pending-request note, same quoting of the latest line — minus the question,
    which lives in `eval/scorers/address_gate.py` so that training and eval cannot drift apart
    (B290).
    """
    lines = str(row.get("context") or "").splitlines()
    convo = "\n".join(lines[-n_context:]) if n_context else ""
    convo = convo.strip() or "(nothing yet)"

    pending = int(row.get("pending_requests") or 0)
    note = (
        f"\n(The assistant still owes the User an answer to {pending} earlier "
        f"request{'s' if pending > 1 else ''}.)"
        if pending
        else ""
    )
    speaker = str(row.get("speaker") or "User")
    turn = str(row.get("current_turn") or "").strip()
    return f"Conversation so far:\n{convo}{note}\n\nLatest line, {speaker}: \"{turn}\""


def convert_address_rows(dataset, n_context: int = CONTEXT_LINES) -> list[dict]:
    """Map raw `gate_synthetic.jsonl` rows to the pipeline's `{text, label, bucket, ...}` shape.

    A row missing `current_turn` or `addressed` is dropped rather than defaulted: `addressed` is
    the label, and a default would invent ground truth.
    """
    out: list[dict] = []
    for raw in dataset:
        if not isinstance(raw, dict):
            continue
        if any(raw.get(field) is None for field in REQUIRED_RAW_FIELDS):
            continue
        if not str(raw.get("current_turn") or "").strip():
            continue
        out.append(
            {
                "text": render_text(raw, n_context),
                "label": ADDRESSED if bool(raw["addressed"]) else NOT_ADDRESSED,
                # Diagnostic fields. `bucket` drives per-bucket accuracy and the failure taxonomy;
                # the other two are for reading `failures.jsonl` by hand and are never scored.
                "bucket": str(raw.get("bucket") or ""),
                "bucket_name": str(raw.get("bucket_name") or ""),
                "rationale": str(raw.get("rationale") or ""),
            }
        )
    return out


def _bundle_path() -> str:
    return os.path.join(LOCAL_BUNDLE, CORPUS_FILE)


def _verify_checksum(path: str, log) -> None:
    """Warn, loudly, if the vendored corpus is not the one the manifest describes.

    Not fatal: a run that is deliberately pointed at a regenerated corpus should be able to
    proceed. But it must say so, because every number it produces is then against a different
    dataset than the one in the notes.
    """
    checksums = os.path.join(LOCAL_BUNDLE, "checksums.sha256")
    if not os.path.exists(checksums):
        return
    expected = {}
    with open(checksums, encoding="utf-8") as handle:
        for line in handle:
            parts = line.split()
            if len(parts) == 2:
                expected[parts[1]] = parts[0]
    want = expected.get(CORPUS_FILE)
    if not want:
        return
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    got = digest.hexdigest()
    if got != want:
        log(f"  [address_bench] WARNING: {CORPUS_FILE} sha256 {got[:12]} != manifest {want[:12]}")
        log("  [address_bench] the corpus has changed; results are NOT comparable to prior runs")


def _read_corpus(log) -> list[dict]:
    path = _bundle_path()
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"address_bench corpus not found at {path}. There is no HuggingFace mirror and no "
            f"live fetch for this dataset — it is vendored. Restore it from "
            f"bubble-agent-pipeline/data/bench/gate_synthetic.jsonl "
            f"(see {LOCAL_BUNDLE}/manifest.json)."
        )
    _verify_checksum(path, log)
    rows = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def load_address_bench(max_train: int, max_test: int, log=print):
    """`(train_rows, eval_rows)`, deduplicated then stratified on (bucket, label).

    Caps are honoured per stratum proportionally, so a truncated train half keeps the bucket mix of
    the full one instead of taking whatever the first N rows happened to be.
    """
    raw = _read_corpus(log)
    rows = convert_address_rows(raw)
    log(f"  [address_bench] {len(rows)} rows from {_bundle_path()}")

    # Deduplicate BEFORE splitting, so no copy of a row lands on both sides of the firewall.
    seen: set[str] = set()
    unique: list[dict] = []
    for row in rows:
        key = _normalize(row["text"])
        if key in seen:
            continue
        seen.add(key)
        unique.append(row)
    if len(unique) != len(rows):
        log(f"  [address_bench] dropped {len(rows) - len(unique)} duplicate row(s) before split")

    # Stratify on (bucket, label). Bucket already determines label in the upstream corpus, but
    # pairing them keeps the split correct for any bundle where it does not.
    strata: dict[tuple[str, str], list[dict]] = {}
    for row in unique:
        strata.setdefault((row["bucket"], row["label"]), []).append(row)

    rng = random.Random(SPLIT_SEED)
    train_pool: list[dict] = []
    eval_pool: list[dict] = []
    for key in sorted(strata):
        group = strata[key]
        rng.shuffle(group)
        n_eval = max(1, round(len(group) * EVAL_FRACTION)) if len(group) > 1 else 0
        eval_pool.extend(group[:n_eval])
        train_pool.extend(group[n_eval:])

    rng.shuffle(train_pool)
    rng.shuffle(eval_pool)

    train = train_pool[: max(0, int(max_train))]
    test = eval_pool[: max(0, int(max_test))]
    n_addressed = sum(1 for row in train if row["label"] == ADDRESSED)
    log(
        f"  [address_bench] train={len(train)} ({n_addressed} addressed) "
        f"eval={len(test)} across {len({r['bucket'] for r in test})} bucket(s)"
    )
    return train, test
