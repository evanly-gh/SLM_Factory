# Per-row firewall reporting is bounded: a pathological rebuild could otherwise blocklist
# thousands of rows and bury the log in the very noise this reporting exists to replace.
_FIREWALL_LOG_LIMIT = int(os.environ.get("SLM_FIREWALL_LOG_LIMIT", "20"))


ARTIFACTS_DIR = "artifacts"

# One canonical name per rebuild KIND, keyed by the `_strategy_origin` each producer stamps on
# its rows. "data_rebuild" in a trajectory is ambiguous — a single rebuild runs the plan's
# strategy and then fills the rest of the curriculum from the train pool, and mining new real
# rows, targeting a confusion pair and drawing gold rows from the pool are three very different
# interventions with three different expected effects. Every rebuild names the kinds that actually
# contributed rows, so a log line stating `data_rebuild` always resolves to what ran.
#
# The names say what the producer DOES, because the previous ones did not. `resample-fill` read as
# a leftover of the removed `resample` STRATEGY when it is in fact the universal filler that
# supplies every curriculum's gold rows, and `fill-synth` was one character away from the
# `synth-fill` padding path that was deleted on 2026-08-16 — so the log appeared to be running a
# mechanism that no longer exists.
REBUILD_KIND_NAMES: dict[str, str] = {
    # Gold rows drawn from the run's existing real train pool. This is how EVERY curriculum is
    # assembled; it is not an orchestrator-selectable strategy — see agent/data_rebuild.py.
    "resample": "train-pool-gold",
    "mine_new_real_source": "mine-new-real",
    "surgical_synthesize": "surgical-synth",
    # Teacher-generated rows balanced across the label space, under the `synthesize` strategy.
    "synthesize": "balanced-synth",
}

# Row provenance tags that mean "this row was generated by the teacher", whichever path made it.
# The composition report used to count only "synthetic" (the plan's synthesize strategy), so
# generation-family positives were reported as unattributed and the dataset looked like it
# contained almost no synthetic data at all when most of the synthesis budget went there.
# `synthetic_fill` is retained ONLY so historical datasets and resumed checkpoints written before
# 2026-08-16 still count correctly; no code path produces it.
SYNTHETIC_PROVENANCE_TAGS = ("synthetic", "synthetic_fill", "synthetic_positive")

# Row provenance tags that mean "this row is real, human-authored data from the train pool".
# Kept next to the synthetic tags because `n_gold` is defined as their sum.
GOLD_PROVENANCE_TAGS = ("train_anchor", "resample")


def rebuild_kind_name(strategy_origin: str) -> str:
    """Canonical human name for a rebuild sub-strategy, for logs and artifacts."""
    return REBUILD_KIND_NAMES.get(str(strategy_origin), str(strategy_origin))


